/*
 * curriculum.js — расширенный каталог тем начальной школы (1–2 классы).
 * Компактный формат темы: теория одной HTML-строкой, вопросы массивами
 * [вопрос, варианты, индексВерного, объяснение, тип?].
 * Конструктор разворачивает их в полный формат COURSE_TOPICS (topics.js).
 */

function addCurriculumTopics(topics) {
  const makeQuestion = (id, row) => {
    const [question, answers, correctAnswer, explanation, type] = row;
    if (type === 'input' || !answers) {
      return { id, type: 'input', question, answers: null, correctAnswer, explanation, rule: explanation };
    }
    const resolved = type || (Array.isArray(correctAnswer) ? 'multi' : 'single');
    return { id, type: resolved, question, answers, correctAnswer, explanation, rule: explanation };
  };

  topics.forEach(topic => {
    const tests = topic.tests.map((test, testIndex) => ({
      id: `${topic.id}-t${testIndex + 1}`,
      title: test.title,
      difficulty: test.difficulty || 2,
      estimatedTime: test.estimatedTime || Math.max(3, Math.round(test.questions.length * 0.8)),
      questions: test.questions.map((row, index) => makeQuestion(`${topic.id}-t${testIndex + 1}q${index + 1}`, row))
    }));

    COURSE_TOPICS.push({
      id: topic.id,
      grade: topic.grade,
      subjectId: topic.subjectId,
      section: topic.section,
      title: topic.title,
      description: topic.description,
      difficulty: topic.difficulty || 'easy',
      theoryHtml: topic.theory,
      practiceQuestions: topic.tests[0].questions.slice(0, 3).map((row, index) => makeQuestion(`${topic.id}-p${index + 1}`, row)),
      tests
    });
  });
}

